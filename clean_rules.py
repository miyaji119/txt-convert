"""文本清理规则配置

集中管理文本格式优化的正则规则，方便不同小说复用。
按功能分组：广告过滤、标题修正、内容分离、引用分离。
"""

import re

# ==================== 广告/垃圾行过滤规则 ====================
# 匹配到这些模式的行将被直接删除
SKIP_PATTERNS = [
    r'进入阅读模式',
    r'长/腿.*老/阿/姨.*整/理',
    r'婆婆推文舍.*更',
    r'.*整/理.*更',           # 泛化：任意"整/理...更"水印
    r'^\s*\d+/\d+/\d+\s*$',   # 阅读进度，如 297/81029/58
    r'扣.*群.*追.*更',
    r'扣[、\\\.]',
    r'月雾阁BL小说',
    r'^[一二三四五六七八九十]+群:\d+',
    r'资源来自互联网.*侵权告知则删',
]

# ==================== 标题修正规则 ====================

# 番外/外篇标题前缀逗号修正：，番外xxx → 番外xxx
FANWAI_PREFIX_COMMA = re.compile(r'^[，,]\s*(番外.*|外篇.*|终章.*|楔子.*)$')

# 直接匹配外篇标题（无前缀逗号的情况）
DIRECT_FANWAI = re.compile(r'^(外篇：.*)\s*$')

# 章节标题（第X章，独立一行）
CHAPTER_TITLE = re.compile(r'^第[零一二三四五六七八九十百千万\d]+章\s*$')

# 番外数字后缀转中文：番外三 xxx1 → 番外三 xxx（一）
FANWAI_NUM_SUFFIX = re.compile(r'^(番外三\s+.*?)([123])\s*$')

# 外篇数字编号转中文（匹配全角/半角括号）：外篇：xxx（3）→ 外篇：xxx（三）
WAIPIAN_NUM = re.compile(r'^(外篇：.*?)[（(]([34])[）)]$')

# 特殊章节标题（精确匹配）
SPECIAL_TITLES = {'终章', '楔子'}

# 特殊标题前缀修正（带逗号前缀）
SPECIAL_TITLE_PREFIX = re.compile(r'^[，,]\s*(番外停更通知)$')

# ==================== 内容分离规则 ====================

# 警告内容行（可能和正文粘连）
WARNING_LINE = re.compile(r'^\s*警告本章含有以下可能让您不适的内容：')

# 分隔符（用于粘连分离）
SEPARATOR = re.compile(r'-{10,}')

# 纯分隔符行（整行都是分隔符）
SEPARATOR_ONLY = re.compile(r'^-{10,}$')

# 行首多余逗号（非标题行）
LEADING_COMMA = re.compile(r'^[，,]\s*\S')

# ==================== 引用分离规则 ====================

# 引用行前缀
QUOTE_PREFIX = '——《'

# 引用中书名与作者的分割标记
QUOTE_SEPARATOR = '》／'

# 作者名后的正文关键词（人称代词/连词等，用于判断引用结束）
BODY_START_KEYWORDS = ('她', '他', '它', '那', '这', '于', '不', '而', '但',
                       '其', '所', '为', '从', '当', '在', '后')

# 作者名最大长度（超出则认为后面有正文）
MAX_AUTHOR_LENGTH = 50

# ==================== 行清理规则 ====================

# 单独的标点行（直接删除）
LONE_PUNCTUATION = ('，', ',', '、')

# 连续空行最大数量
MAX_BLANK_LINES = 2

# ==================== 数字映射 ====================

NUM_MAP = {'1': '一', '2': '二', '3': '三', '4': '四',
           '5': '五', '6': '六', '7': '七', '8': '八', '9': '九'}

# ==================== 去重规则 ====================
# 检测到这些标记时截断后续内容（去重复）
DEDUP_MARKERS = ('<!--', 'EasyPub元数据')

# ==================== 元数据/标记行过滤 ====================
METADATA_PREFIXES = ('<!--', '-->', '===', '书名:', '作者:', '生成时间:',
                     '章节数:', '文件大小:', 'EasyPub元数据')
END_MARKERS = {'END', 'end', 'To be continued', 'To　be　continued', 'TO BE CONTINUED'}

# ==================== 数字章节转换规则 ====================
PURE_NUMBER = re.compile(r'^\d+$')                        # 纯数字行 → 第N章
NUMBER_TEXT = re.compile(r'^(\d+)\s+(\S.*)$')             # 数字+正文 → 分离
LABEL_PATTERN = re.compile(r'^\d+\s+一发完结')              # 标签行（不转换）

# ==================== 番外国师编号规则 ====================
GUOSHI_NUM = re.compile(r'^番外\s+国师\s+(\d+)$')          # 番外 国师 2 → 番外 国师（二）
GUOSHI_TEXT = re.compile(r'^番外\s+国师\s+(\S.*)$')        # 番外 国师 正文 → 分离
ZHIMA_LABEL = re.compile(r'^(番外\s+芝麻糊)\s*[（(].*$')   # 番外 芝麻糊 （标签）→ 去标签

# ==================== 预编译跳过模式 ====================

SKIP_PATTERNS_COMPILED = [re.compile(p) for p in SKIP_PATTERNS]
